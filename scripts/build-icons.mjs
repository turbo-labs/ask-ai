// Inlines assets/*.png into src/icons.ts as data URIs, so the component needs
// no bundler image loader and no files copied into the host site's public/.
import { readFileSync, writeFileSync } from "node:fs"

const ids = ["chatgpt", "claude", "perplexity", "grok", "gemini", "copilot", "mistral"]
const root = new URL("..", import.meta.url)

const entries = ids.map((id) => {
  const b64 = readFileSync(new URL(`assets/${id}.png`, root)).toString("base64")
  return `  ${id}: "data:image/png;base64,${b64}",`
})

writeFileSync(
  new URL("src/icons.ts", root),
  `// Generated by scripts/build-icons.mjs from assets/*.png. Do not edit.\nexport const icons: Record<string, string> = {\n${entries.join("\n")}\n}\n`,
)
